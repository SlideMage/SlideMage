"""Write packaging/tex-requirements.toml (and the release signing keys) into the installers.

    python packaging/tex_requirements.py            rewrite the generated parts
    python packaging/tex_requirements.py --check    exit 1 when a generated part differs (tests/test_tex_requirements.py)

The generated parts sit between "BEGIN generated by packaging/tex_requirements.py" and "END generated by ..." lines:
in packaging/install-slidemage.sh (shell variables) and in packaging/slidemage-tex.iss, which packaging/slidemage.iss
includes (#define lines). Everything else in those files is written by hand.
"""
from __future__ import annotations

import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
REQUIREMENTS = HERE / "tex-requirements.toml"
SHELL_SCRIPT = HERE / "install-slidemage.sh"
INNO_INCLUDE = HERE / "slidemage-tex.iss"
BEGIN = "BEGIN generated by packaging/tex_requirements.py"
END = "END generated by packaging/tex_requirements.py"


def load(path: Path = REQUIREMENTS) -> dict:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    for entry in data["tex"]:
        if not {"file", "ctan"} <= set(entry):
            raise ValueError(f"{path.name}: a [[tex]] entry needs file and ctan: {entry}")
    for program in data["programs"]:
        if not {"name", "ctan", "debian", "fedora"} <= set(program):
            raise ValueError(f"{path.name}: a program needs name, ctan, debian and fedora: {program}")
    return data


def trusted_keys() -> list[str]:
    sys.path.insert(0, str(ROOT / "src"))
    try:
        from slidemage import release_signing
    finally:
        sys.path.pop(0)
    return [key.hex() for key in release_signing.parse_keys(release_signing.TRUSTED_PUBLIC_KEYS)]


def _pairs(items, key: str, name_key: str = "file") -> str:
    return " ".join(f"{item[name_key]}:{item[key]}" for item in items if item.get(key))


def shell_block(data: dict, keys: list[str]) -> str:
    required = [e for e in data["tex"] if not e.get("optional")]
    optional = [e for e in data["tex"] if e.get("optional")]
    lines = [
        "# Files kpsewhich must find, and the package that ships each (file:package), per package manager.",
        f'TEX_REQUIRED="{" ".join(e["file"] for e in required)}"',
        f'TEX_OPTIONAL="{" ".join(e["file"] for e in optional)}"',
        f'APT_TEX="{_pairs(data["tex"], "debian")}"',
        f'DNF_TEX="{_pairs(data["tex"], "fedora")}"',
        f'TLMGR_TEX="{_pairs(data["tex"], "ctan")}"',
        "# Programs on PATH (program:package).",
        f'APT_PROGRAMS="{_pairs(data["programs"], "debian", "name")}"',
        f'DNF_PROGRAMS="{_pairs(data["programs"], "fedora", "name")}"',
        f'TLMGR_PROGRAMS="{_pairs(data["programs"], "ctan", "name")}"',
        "# The release signing keys (src/slidemage/release_signing.py, TRUSTED_PUBLIC_KEYS), Ed25519, hex.",
        f'TRUSTED_KEYS="{" ".join(keys)}"',
    ]
    return "\n".join(lines)


def inno_block(data: dict) -> str:
    packages: list[str] = []
    for item in [*data["programs"], *data["tex"]]:
        name = item.get("miktex") or item["ctan"]
        if item.get("name") == "kpsewhich" or item.get("name") == "lualatex":
            continue        # part of every MiKTeX installation
        if name not in packages:
            packages.append(name)
    required = [e["file"] for e in data["tex"] if not e.get("optional")]
    return "\n".join([
        "; MiKTeX packages installed up front (miktex packages require: only those missing), and the files the setup",
        "; checks with kpsewhich afterwards.",
        f'#define MiktexPackages "{" ".join(packages)}"',
        f'#define TexRequiredFiles "{" ".join(required)}"',
    ])


def replace_block(text: str, block: str, comment: str) -> str:
    begin, end = f"{comment} {BEGIN}", f"{comment} {END}"
    start = text.index(begin) + len(begin)
    stop = text.index(end)
    return text[:start] + "\n" + block + "\n" + text[stop:]


def generated() -> dict[Path, str]:
    """{file: its text with the generated part as it should be}."""
    data = load()
    return {
        SHELL_SCRIPT: replace_block(SHELL_SCRIPT.read_text(encoding="utf-8"), shell_block(data, trusted_keys()), "#"),
        INNO_INCLUDE: replace_block(INNO_INCLUDE.read_text(encoding="utf-8"), inno_block(data), ";"),
    }


def main(argv: list[str]) -> int:
    stale = []
    for path, text in generated().items():
        if path.read_text(encoding="utf-8") != text:
            stale.append(path)
            if "--check" not in argv:
                path.write_text(text, encoding="utf-8", newline="\n")
    if "--check" in argv and stale:
        print("out of date (run python packaging/tex_requirements.py):", *[p.name for p in stale])
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
