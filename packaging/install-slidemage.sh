# Install SlideMage for this user on Linux, with the TeX and system packages it needs.
#
#   curl -fsSL https://github.com/SlideMage/SlideMage/releases/latest/download/install-slidemage.sh | bash
#   bash install-slidemage.sh [--yes] [--uninstall] [--from-zip FILE [--unsigned]] [--no-packages] [--no-self-test]
#
# What it does (it lists everything and asks first, unless --yes):
#   1. Checks the system: x86_64, glibc 2.39 or newer (Ubuntu 24.04, Debian 13, Fedora 40 and later).
#   2. With apt or dnf: installs the missing system libraries and TeX packages (only this step uses sudo). A TeX
#      installation that already has a file SlideMage needs is left alone for that file; an upstream TeX Live
#      (tlmgr, e.g. in /usr/local/texlive) is never mixed with the distribution's TeX: the script prints the tlmgr
#      command for what is missing instead.
#   3. Downloads SlideMage-linux-folder.zip of the latest release and checks its signature (the .sig beside it,
#      Ed25519, the keys SlideMage itself trusts) before unpacking anything.
#   4. Unpacks it to ~/.local/share/SlideMage (the folder SlideMage updates itself in), links ~/.local/bin/slidemage,
#      and adds the menu entry and the icon.
#   5. Runs `SlideMage --self-test` and `SlideMage --self-test --compile` (compiles a deck per layout with a citation).
# Running it again repairs or updates the installation. It never touches projects or settings (~/.config/SlideMage).
#
# Options:
#   --yes            do not ask (needed when there is no terminal to ask on)
#   --uninstall      remove SlideMage, its link, menu entry and icon; leaves settings, projects and system packages
#   --from-zip FILE  install FILE instead of downloading (offline, tests); its signature is FILE.sig
#   --unsigned       with --from-zip: install a zip without a signature (a build of your own)
#   --no-packages    install no system or TeX packages, only SlideMage
#   --no-self-test   skip step 5
#
# Kept in packaging/ of the SlideMage repository and attached to every release under this name. Tested in Docker
# by tests/installer/ (README there).
set -euo pipefail

REPOSITORY="SlideMage/SlideMage"
ASSET="SlideMage-linux-folder.zip"
DOWNLOAD="https://github.com/$REPOSITORY/releases/latest/download"
MIN_GLIBC="2.39"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
INSTALL_DIR="$DATA_HOME/SlideMage"
BIN_DIR="$HOME/.local/bin"
LINK="$BIN_DIR/slidemage"
DESKTOP_FILE="$DATA_HOME/applications/slidemage.desktop"
ICON_FILE="$DATA_HOME/icons/hicolor/scalable/apps/slidemage.svg"

# BEGIN generated by packaging/tex_requirements.py
# Files kpsewhich must find, and the package that ships each (file:package), per package manager.
TEX_REQUIRED="beamer.cls biblatex.sty booktabs.sty colortbl.sty etoolbox.sty fontspec.sty geometry.sty hyperref.sty scrlfile.sty listings.sty tikz.sty pgfplots.sty pifont.sty pzdr.tfm translator.sty xcolor.sty xfp.sty lua-uni-case.lua luaotfload.sty lmroman10-regular.otf lmsans10-regular.otf lmmono10-regular.otf"
TEX_OPTIONAL="sansmathaccent.sty"
APT_TEX="beamer.cls:texlive-latex-recommended biblatex.sty:texlive-bibtex-extra booktabs.sty:texlive-latex-recommended colortbl.sty:texlive-latex-base etoolbox.sty:texlive-latex-recommended fontspec.sty:texlive-latex-recommended geometry.sty:texlive-latex-base hyperref.sty:texlive-latex-base scrlfile.sty:texlive-latex-recommended listings.sty:texlive-latex-recommended tikz.sty:texlive-pictures pgfplots.sty:texlive-pictures pifont.sty:texlive-latex-base pzdr.tfm:texlive-fonts-recommended translator.sty:texlive-latex-recommended xcolor.sty:texlive-latex-recommended xfp.sty:texlive-latex-base lua-uni-case.lua:texlive-luatex luaotfload.sty:texlive-luatex lmroman10-regular.otf:fonts-lmodern lmsans10-regular.otf:fonts-lmodern lmmono10-regular.otf:fonts-lmodern"
DNF_TEX="beamer.cls:texlive-beamer biblatex.sty:texlive-biblatex booktabs.sty:texlive-booktabs colortbl.sty:texlive-colortbl etoolbox.sty:texlive-etoolbox fontspec.sty:texlive-fontspec geometry.sty:texlive-geometry hyperref.sty:texlive-hyperref scrlfile.sty:texlive-koma-script listings.sty:texlive-listings tikz.sty:texlive-pgf pgfplots.sty:texlive-pgfplots pifont.sty:texlive-psnfss pzdr.tfm:texlive-zapfding translator.sty:texlive-translator xcolor.sty:texlive-xcolor xfp.sty:texlive-l3packages lua-uni-case.lua:texlive-lua-uni-algos luaotfload.sty:texlive-luaotfload lmroman10-regular.otf:texlive-lm lmsans10-regular.otf:texlive-lm lmmono10-regular.otf:texlive-lm sansmathaccent.sty:texlive-sansmathaccent"
TLMGR_TEX="beamer.cls:beamer biblatex.sty:biblatex booktabs.sty:booktabs colortbl.sty:colortbl etoolbox.sty:etoolbox fontspec.sty:fontspec geometry.sty:geometry hyperref.sty:hyperref scrlfile.sty:koma-script listings.sty:listings tikz.sty:pgf pgfplots.sty:pgfplots pifont.sty:psnfss pzdr.tfm:zapfding translator.sty:translator xcolor.sty:xcolor xfp.sty:l3packages lua-uni-case.lua:lua-uni-algos luaotfload.sty:luaotfload lmroman10-regular.otf:lm lmsans10-regular.otf:lm lmmono10-regular.otf:lm sansmathaccent.sty:sansmathaccent"
# Programs on PATH (program:package).
APT_PROGRAMS="lualatex:texlive-latex-base latexmk:latexmk biber:biber kpsewhich:texlive-binaries"
DNF_PROGRAMS="lualatex:texlive-luahbtex latexmk:latexmk biber:biber kpsewhich:texlive-kpathsea"
TLMGR_PROGRAMS="lualatex:luatex latexmk:latexmk biber:biber kpsewhich:kpathsea"
# The release signing keys (src/slidemage/release_signing.py, TRUSTED_PUBLIC_KEYS), Ed25519, hex.
TRUSTED_KEYS="3346c1d7aad53ae10b6a8835bb81489b2f133dbd58e8d2bb2eb8379c0bba1d90"
# END generated by packaging/tex_requirements.py

# System libraries of the Qt and Qt WebEngine (Chromium) build, per package manager.
APT_LIBRARIES="libegl1 libgl1 libopengl0 libxkbcommon0 libxkbcommon-x11-0 libdbus-1-3 libfontconfig1 libfreetype6
  libglib2.0-0t64 libxcb-cursor0 libxcb-icccm4 libxcb-image0 libxcb-keysyms1 libxcb-render-util0 libxcb-shape0
  libxcb-xinerama0 libxcb-xkb1 libxcb-randr0 libx11-xcb1 libnss3 libxcomposite1 libxdamage1 libxrandr2 libxtst6
  libxkbfile1 libxfixes3 libgssapi-krb5-2 libasound2t64"
DNF_LIBRARIES="mesa-libEGL mesa-libGL libglvnd-opengl libxkbcommon libxkbcommon-x11 dbus-libs fontconfig freetype
  glib2 xcb-util-cursor xcb-util-wm xcb-util-image xcb-util-keysyms xcb-util-renderutil libxcb libX11-xcb nss
  libXcomposite libXdamage libXrandr libXtst libxkbfile libXfixes krb5-libs alsa-lib"

ASSUME_YES=0
UNINSTALL=0
FROM_ZIP=""
UNSIGNED=0
PACKAGES=1
SELF_TEST=1

say() { printf '%s\n' "$*"; }
warn() { printf 'SlideMage installer: %s\n' "$*" >&2; }
die() { warn "$*"; exit 1; }

usage() { sed -n '2,/^set -euo/p' "$0" | sed -n 's/^# \{0,1\}//p'; }

while [ $# -gt 0 ]; do
  case "$1" in
    --yes|-y) ASSUME_YES=1 ;;
    --uninstall) UNINSTALL=1 ;;
    --from-zip) [ $# -ge 2 ] || die "--from-zip needs a file"; FROM_ZIP="$2"; shift ;;
    --unsigned) UNSIGNED=1 ;;
    --no-packages) PACKAGES=0 ;;
    --no-self-test) SELF_TEST=0 ;;
    --help|-h) usage; exit 0 ;;
    *) die "unknown option $1 (try --help)" ;;
  esac
  shift
done
[ "$UNSIGNED" = 0 ] || [ -n "$FROM_ZIP" ] || die "--unsigned only goes with --from-zip"

# Questions go to the terminal: with `curl ... | bash` the standard input is the script itself.
ask() {
  [ "$ASSUME_YES" = 1 ] && return 0
  local answer
  if ! { exec 3</dev/tty; } 2>/dev/null; then
    die "no terminal to ask on: run again with --yes"
  fi
  printf '%s [y/N] ' "$1" > /dev/tty
  read -r answer <&3 || answer=""
  exec 3<&-
  case "$answer" in y|Y|yes|Yes|YES) return 0 ;; *) return 1 ;; esac
}

version_at_least() {   # version_at_least HAVE NEED
  [ "$(printf '%s\n%s\n' "$2" "$1" | sort -V | head -n1)" = "$2" ]
}

# --- uninstall ----------------------------------------------------------------------------------------------------

uninstall() {
  say "Removing SlideMage from $INSTALL_DIR (settings in ~/.config/SlideMage and your projects stay)."
  ask "Remove SlideMage?" || exit 1
  rm -rf "$INSTALL_DIR" "$INSTALL_DIR.old" "$INSTALL_DIR.update"
  if [ -L "$LINK" ] && [ "$(readlink "$LINK")" = "$INSTALL_DIR/SlideMage" ]; then rm -f "$LINK"; fi
  rm -f "$DESKTOP_FILE" "$ICON_FILE"
  command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database -q "$DATA_HOME/applications" || true
  say "SlideMage is removed. The system and TeX packages it installed are still there."
}

if [ "$UNINSTALL" = 1 ]; then uninstall; exit 0; fi

# --- 1. the system ------------------------------------------------------------------------------------------------

[ "$(uname -s)" = "Linux" ] || die "this installer is for Linux (Windows: SlideMage-Setup.exe)"
[ "$(uname -m)" = "x86_64" ] || die "SlideMage is built for x86_64 only, this computer is $(uname -m)"
if [ "$(id -u)" = 0 ]; then
  die "run this as your own user, not as root: it installs SlideMage for you and uses sudo only for system packages"
fi
GLIBC="$(getconf GNU_LIBC_VERSION 2>/dev/null | awk '{print $2}')"
[ -n "$GLIBC" ] || die "no GNU C library found (SlideMage needs glibc $MIN_GLIBC or newer)"
version_at_least "$GLIBC" "$MIN_GLIBC" ||
  die "SlideMage needs glibc $MIN_GLIBC or newer (Ubuntu 24.04, Debian 13, Fedora 40); this system has $GLIBC"

PM=""
if command -v apt-get >/dev/null 2>&1; then PM=apt
elif command -v dnf >/dev/null 2>&1; then PM=dnf
fi

installed() {   # installed PACKAGE: is the distribution package installed?
  case "$PM" in
    apt) [ "$(dpkg-query -W -f='${Status}' "$1" 2>/dev/null)" = "install ok installed" ] ;;
    dnf) rpm -q --whatprovides "$1" >/dev/null 2>&1 ;;
  esac
}

package_for() {   # package_for KEY PAIRS: the package after "KEY:" in "a:x b:y", or nothing
  local pair
  for pair in $2; do
    if [ "${pair%%:*}" = "$1" ]; then printf '%s' "${pair#*:}"; return; fi
  done
}

add_unique() {   # add_unique VAR WORD...
  local var="$1" word; shift
  for word in "$@"; do
    case " ${!var} " in *" $word "*) ;; *) printf -v "$var" '%s' "${!var:+${!var} }$word" ;; esac
  done
}

SYSTEM_PACKAGES=""      # distribution packages to install
TLMGR_PACKAGES=""       # missing packages of an upstream TeX Live, for the tlmgr command printed at the end
TEX_KIND="none"

plan_packages() {
  local tools libs tex_pairs program_pairs file program package
  case "$PM" in
    apt) libs="$APT_LIBRARIES"; tex_pairs="$APT_TEX"; program_pairs="$APT_PROGRAMS" ;;
    dnf) libs="$DNF_LIBRARIES"; tex_pairs="$DNF_TEX"; program_pairs="$DNF_PROGRAMS" ;;
  esac
  tools="unzip openssl"
  [ -n "$FROM_ZIP" ] || tools="$tools curl ca-certificates"
  for package in $tools $libs; do installed "$package" || add_unique SYSTEM_PACKAGES "$package"; done

  local kpsewhich
  kpsewhich="$(command -v kpsewhich || true)"
  if [ -n "$kpsewhich" ] && command -v tlmgr >/dev/null 2>&1 && tlmgr --version >/dev/null 2>&1 &&
     case "$(readlink -f "$kpsewhich")" in /usr/bin/*) false ;; *) true ;; esac; then
    TEX_KIND="upstream"     # TeX Live from tug.org: never mix in the distribution's TeX packages
    for program in latexmk biber lualatex; do
      command -v "$program" >/dev/null 2>&1 || add_unique TLMGR_PACKAGES "$(package_for "$program" "$TLMGR_PROGRAMS")"
    done
    for file in $TEX_REQUIRED $TEX_OPTIONAL; do
      kpsewhich "$file" >/dev/null 2>&1 || add_unique TLMGR_PACKAGES "$(package_for "$file" "$TLMGR_TEX")"
    done
    return
  fi
  TEX_KIND="${kpsewhich:+distribution}"
  TEX_KIND="${TEX_KIND:-none}"
  for program in lualatex latexmk biber kpsewhich; do
    if ! command -v "$program" >/dev/null 2>&1; then
      package="$(package_for "$program" "$program_pairs")"
      [ -z "$package" ] || installed "$package" || add_unique SYSTEM_PACKAGES "$package"
    fi
  done
  for file in $TEX_REQUIRED $TEX_OPTIONAL; do
    if [ -z "$kpsewhich" ] || ! kpsewhich "$file" >/dev/null 2>&1; then
      package="$(package_for "$file" "$tex_pairs")"
      [ -z "$package" ] || installed "$package" || add_unique SYSTEM_PACKAGES "$package"
    fi
  done
}

if [ "$PACKAGES" = 1 ]; then
  if [ -z "$PM" ]; then
    warn "neither apt nor dnf found: install LuaLaTeX, latexmk, biber and these TeX files yourself: $TEX_REQUIRED"
    PACKAGES=0
  else
    plan_packages
  fi
fi

# --- what will happen ---------------------------------------------------------------------------------------------

say "SlideMage will be installed for $(id -un) in $INSTALL_DIR"
say "  command: $LINK   menu entry: $DESKTOP_FILE"
if [ -n "$FROM_ZIP" ]; then say "  from: $FROM_ZIP"; else say "  from: $DOWNLOAD/$ASSET (latest release)"; fi
if [ -n "$SYSTEM_PACKAGES" ]; then
  say "System packages to install with sudo ($PM):"
  printf '%s\n' $SYSTEM_PACKAGES | sed 's/^/  /' | paste -sd' ' | fold -s -w 110 | sed 's/^/ /'
elif [ "$PACKAGES" = 1 ]; then
  say "No system packages are missing."
fi
if [ -n "$TLMGR_PACKAGES" ]; then
  say "Your TeX Live (tlmgr) lacks: $TLMGR_PACKAGES -- the command to add them is shown at the end."
fi
ask "Continue?" || { say "Nothing was changed."; exit 1; }

# --- 2. system and TeX packages -----------------------------------------------------------------------------------

if [ -n "$SYSTEM_PACKAGES" ]; then
  command -v sudo >/dev/null 2>&1 || die "sudo is needed to install: $SYSTEM_PACKAGES"
  say "Installing system packages (this can take several minutes for TeX) ..."
  # shellcheck disable=SC2086
  case "$PM" in
    apt) sudo env DEBIAN_FRONTEND=noninteractive apt-get update -q &&
         sudo env DEBIAN_FRONTEND=noninteractive apt-get install -y -q --no-install-recommends $SYSTEM_PACKAGES ;;
    dnf) sudo dnf install -y -q --setopt=install_weak_deps=False $SYSTEM_PACKAGES ;;
  esac
fi

# --- 3. download and verify ---------------------------------------------------------------------------------------

WORK="$(mktemp -d "${TMPDIR:-/tmp}/slidemage-install.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
ZIP="$WORK/$ASSET"
if [ -n "$FROM_ZIP" ]; then
  [ -f "$FROM_ZIP" ] || die "no such file: $FROM_ZIP"
  cp "$FROM_ZIP" "$ZIP"
  [ ! -f "$FROM_ZIP.sig" ] || cp "$FROM_ZIP.sig" "$ZIP.sig"
else
  say "Downloading $ASSET ..."
  curl -fL --proto '=https' --tlsv1.2 --retry 3 -o "$ZIP" "$DOWNLOAD/$ASSET" || die "the download failed"
  curl -fsL --proto '=https' --tlsv1.2 --retry 3 -o "$ZIP.sig" "$DOWNLOAD/$ASSET.sig" ||
    die "the release has no signature file $ASSET.sig: not installing it"
fi

hex_to_binary() { printf '%b' "$(printf '%s' "$1" | sed 's/../\\x&/g')"; }

verify_signature() {   # the message release_signing.signed_message() signs, checked against every trusted key
  local sha key
  sha="$(sha256sum "$ZIP" | awk '{print $1}')"
  printf 'SlideMage release v1\n%s\n%s\n' "$ASSET" "$sha" > "$WORK/message"
  base64 -d < "$ZIP.sig" > "$WORK/signature" 2>/dev/null || return 1
  for key in $TRUSTED_KEYS; do
    # An Ed25519 public key as PEM: the fixed SubjectPublicKeyInfo prefix, then the 32 key bytes.
    { hex_to_binary "302a300506032b6570032100"; hex_to_binary "$key"; } > "$WORK/key.der"
    openssl pkey -pubin -inform DER -in "$WORK/key.der" -out "$WORK/key.pem" 2>/dev/null || continue
    if openssl pkeyutl -verify -pubin -inkey "$WORK/key.pem" -rawin -in "$WORK/message" \
         -sigfile "$WORK/signature" >/dev/null 2>&1; then
      return 0
    fi
  done
  return 1
}

if [ -f "$ZIP.sig" ]; then
  command -v openssl >/dev/null 2>&1 || die "openssl is needed to check the signature (install it, or use --no-packages only after installing it)"
  verify_signature || die "the signature of $ASSET does not match SlideMage's release keys: not installing it"
  say "Signature checked."
elif [ "$UNSIGNED" = 1 ]; then
  warn "installing $FROM_ZIP without a signature (--unsigned)"
else
  die "no signature file $FROM_ZIP.sig (use --unsigned for a build of your own)"
fi

# --- 4. unpack and install ----------------------------------------------------------------------------------------

command -v unzip >/dev/null 2>&1 || die "unzip is needed"
unzip -q "$ZIP" -d "$WORK/unpacked"
NEW="$WORK/unpacked/SlideMage-folder"
[ -f "$NEW/SlideMage" ] && [ -d "$NEW/_internal" ] || die "$ASSET does not hold SlideMage-folder/SlideMage"
chmod +x "$NEW/SlideMage"

if pgrep -f "^$INSTALL_DIR/SlideMage" >/dev/null 2>&1; then
  die "SlideMage is running from $INSTALL_DIR: close it and run the installer again"
fi
mkdir -p "$DATA_HOME"
# Next to the old folder first (same file system), then the swap, so a failure leaves a working installation.
rm -rf "$INSTALL_DIR.installing"
mv "$NEW" "$INSTALL_DIR.installing" 2>/dev/null || cp -a "$NEW" "$INSTALL_DIR.installing"
if [ -e "$INSTALL_DIR" ]; then
  rm -rf "$INSTALL_DIR.replaced"
  mv "$INSTALL_DIR" "$INSTALL_DIR.replaced"
fi
mv "$INSTALL_DIR.installing" "$INSTALL_DIR"
rm -rf "$INSTALL_DIR.replaced"

mkdir -p "$BIN_DIR" "$(dirname "$DESKTOP_FILE")" "$(dirname "$ICON_FILE")"
ln -sfn "$INSTALL_DIR/SlideMage" "$LINK"
# The icon and the menu entry live outside the app folder: SlideMage's updater replaces that folder as a whole.
install -m 644 "$INSTALL_DIR/_internal/slidemage/assets/icon.svg" "$ICON_FILE"
cat > "$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Name=SlideMage
Comment=Compile and manage SlideMage slide decks
Exec=$INSTALL_DIR/SlideMage
Icon=$ICON_FILE
Terminal=false
Categories=Office;
StartupWMClass=SlideMage
EOF
command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database -q "$(dirname "$DESKTOP_FILE")" || true
say "SlideMage is installed in $INSTALL_DIR."

# --- 5. self-tests ------------------------------------------------------------------------------------------------

STATUS=0
if [ "$SELF_TEST" = 1 ]; then
  say "Checking the installation ..."
  QT_QPA_PLATFORM=offscreen "$INSTALL_DIR/SlideMage" --self-test || { warn "SlideMage --self-test failed"; STATUS=1; }
  if command -v latexmk >/dev/null 2>&1; then
    say "Compiling a test deck per layout (the first compile builds the font list and can take a few minutes) ..."
    QT_QPA_PLATFORM=offscreen "$INSTALL_DIR/SlideMage" --self-test --compile ||
      { warn "the test compile failed: see the lines above"; STATUS=1; }
  else
    warn "no latexmk on PATH: SlideMage is installed, but it cannot compile decks until TeX is installed"
    STATUS=1
  fi
fi

if [ -n "$TLMGR_PACKAGES" ]; then
  TLMGR="tlmgr install $TLMGR_PACKAGES"
  [ -w "$(dirname "$(dirname "$(readlink -f "$(command -v tlmgr)")")")" ] || TLMGR="sudo $(command -v tlmgr) install $TLMGR_PACKAGES"
  say "To add what your TeX Live lacks:  $TLMGR"
fi
case ":$PATH:" in
  *":$BIN_DIR:"*) say "Start it from the menu, or with: slidemage" ;;
  *) say "Start it from the menu, or with: $LINK  ($BIN_DIR is not on your PATH yet; it usually is after the next login)" ;;
esac
exit "$STATUS"
