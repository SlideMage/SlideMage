"""Write THIRD_PARTY_NOTICES.md: every package the executable bundles, with its version, licence and home page,
read from the installed package metadata (run it in the environment the release is built in), followed by the notes
that metadata cannot give (fonts, the LaTeX theme, Qt's LGPL terms).

    python tools/third_party_notices.py > THIRD_PARTY_NOTICES.md
"""
from __future__ import annotations

import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIRECT = ("PySide6", "pymupdf", "pillow", "lxml", "python-pptx", "odfpy", "ptyprocess", "pywinpty",
          "keyring")
# What the package metadata of these does not say clearly (checked against their projects).
KNOWN = {
    "pymupdf": "AGPL-3.0-or-later (MuPDF, Artifex Software)",
    "pillow": "MIT-CMU (HPND)",
    "pyside6": "LGPL-3.0-only OR GPL-2.0-only OR GPL-3.0-only (Qt for Python, The Qt Company)",
    "pyside6-essentials": "LGPL-3.0-only OR GPL-2.0-only OR GPL-3.0-only (Qt for Python, The Qt Company)",
    "pyside6-addons": "LGPL-3.0-only OR GPL-2.0-only OR GPL-3.0-only (Qt for Python, The Qt Company)",
    "shiboken6": "LGPL-3.0-only OR GPL-2.0-only OR GPL-3.0-only (Qt for Python, The Qt Company)",
}


def normal(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def licence_of(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    if normal(meta["Name"]) in KNOWN:
        return KNOWN[normal(meta["Name"])]
    expression = meta.get("License-Expression")
    if expression:
        return expression
    text = (meta.get("License") or "").strip()
    if text and len(text) < 80 and "\n" not in text:
        return text
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    return ", ".join(classifiers) or "see the project"


def closure(roots: tuple[str, ...]) -> dict[str, metadata.Distribution]:
    found: dict[str, metadata.Distribution] = {}
    todo = [normal(r) for r in roots]
    while todo:
        name = todo.pop()
        if name in found:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        found[name] = dist
        for requirement in dist.requires or []:
            if "extra ==" in requirement:
                continue
            todo.append(normal(re.split(r"[ ;<>=!~\[(]", requirement, maxsplit=1)[0]))
    return found


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    packages = closure(DIRECT)
    print("# Third-party notices\n")
    print("SlideMage itself is GPL-3.0-or-later (see `LICENSE`). The executable bundles the software below, each under")
    print("its own licence. This file is generated by `tools/third_party_notices.py` from the packages the release was")
    print("built with.\n")
    print("| Package | Version | Licence | Home page |\n|---|---|---|---|")
    for name in sorted(packages):
        meta = packages[name].metadata
        home = meta.get("Home-page") or next(
            (entry.split(",", 1)[1].strip() for entry in meta.get_all("Project-URL") or []), "")
        print(f"| {meta['Name']} | {meta['Version']} | {licence_of(packages[name])} | {home} |")
    print((ROOT / "tools" / "third_party_notices_tail.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    sys.exit(main())
