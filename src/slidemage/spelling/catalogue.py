@dataclass(frozen=True)
class DictFile:
    name: str
    url: str
    size: int
    sha256: str


@dataclass(frozen=True)
class Dictionary:
    """What one language (or one variant of it) needs. `key` names its folder: `fr`, `de_AT`, `en_GB`."""
    key: str
    language: str
    engine: str          # "hunspell" (spylls) or "wordlist" (pyspellchecker)
    label: str           # for the status line: "the German (Austria) dictionary"
    files: tuple[DictFile, ...]

    @property
    def size(self) -> int:
        return sum(f.size for f in self.files)


def file_url(name: str) -> str:
    if name.endswith(".json.gz"):
        return ("https://raw.githubusercontent.com/barrust/pyspellchecker/"
                f"{PYSPELLCHECKER_COMMIT}/spellchecker/resources/{name}")
    return f"https://raw.githubusercontent.com/LibreOffice/dictionaries/{LIBREOFFICE_COMMIT}/{name[:2]}/{name}"


def hunspell_files() -> list[str]:
    """Every Hunspell file name, in catalogue order (tools/spelling_pins.py)."""
    return [f"{_STEMS[language].format(variant=variant)}.{ext}"
            for language, variants in VARIANTS.items() for variant in variants for ext in ("aff", "dic")]


def _file(name: str) -> DictFile:
    size, sha = FILES[name]
    return DictFile(name, file_url(name), size, sha)


def _catalogue() -> dict[str, Dictionary]:
    from .. import languages

    entries = {}
    for language, variants in VARIANTS.items():
        for variant, place in variants.items():
            stem = _STEMS[language].format(variant=variant)
            key = f"{language}_{variant}"
            entries[key] = Dictionary(key, language, "hunspell", f"the {languages.name(language)} ({place}) dictionary",
                                      (_file(f"{stem}.aff"), _file(f"{stem}.dic")))
    for code in PYSPELLCHECKER_LANGUAGES:
        entries[code] = Dictionary(code, code, "wordlist", f"the {languages.name(code)} dictionary",
                                   (_file(f"{code}.json.gz"),))
    return entries


CATALOGUE: dict[str, Dictionary] = _catalogue()


def key_for(language: str, variant: str = "") -> str:
    """The catalogue key of `language` in `variant` (ignored for a language without variants)."""
    language = language.lower()
    if language in VARIANTS:
        return f"{language}_{variant if variant in VARIANTS[language] else DEFAULT_VARIANTS[language]}"
    return language


def dictionary_for(language: str, variant: str = "") -> Dictionary | None:
    """The dictionary that checks `language` (a code as languages.py has it), or None when there is none. An
    unknown or missing variant means the language's default."""
    return CATALOGUE.get(key_for(language, variant))


def supported_languages() -> set[str]:
    return {entry.language for entry in CATALOGUE.values()}
