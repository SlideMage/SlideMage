@dataclass(frozen=True)
class DictFile:
    name: str
    url: str
    size: int
    sha256: str


@dataclass(frozen=True)
class Dictionary:
    """What one language (or German variant) needs. `key` names its folder: `en`, `de_AT`."""
    key: str
    language: str
    engine: str          # "hunspell" (spylls) or "wordlist" (pyspellchecker)
    label: str           # for the status line: "the German (Austria) dictionary"
    files: tuple[DictFile, ...]

    @property
    def size(self) -> int:
        return sum(f.size for f in self.files)


def file_url(name: str) -> str:
    if name.endswith(".json.gz"):
        return ("https://raw.githubusercontent.com/barrust/pyspellchecker/"
                f"{PYSPELLCHECKER_COMMIT}/spellchecker/resources/{name}")
    return f"https://raw.githubusercontent.com/LibreOffice/dictionaries/{LIBREOFFICE_COMMIT}/de/{name}"


def _file(name: str) -> DictFile:
    size, sha = FILES[name]
    return DictFile(name, file_url(name), size, sha)


_VARIANT_NAMES = {"AT": "Austria", "DE": "Germany", "CH": "Switzerland"}


def _catalogue() -> dict[str, Dictionary]:
    from .. import languages

    entries = {}
    for variant in GERMAN_VARIANTS:
        stem = f"de_{variant}_frami"
        entries[f"de_{variant}"] = Dictionary(
            f"de_{variant}", "de", "hunspell", f"the German ({_VARIANT_NAMES[variant]}) dictionary",
            (_file(f"{stem}.aff"), _file(f"{stem}.dic")))
    for code in PYSPELLCHECKER_LANGUAGES:
        entries[code] = Dictionary(code, code, "wordlist", f"the {languages.name(code)} dictionary",
                                   (_file(f"{code}.json.gz"),))
    return entries


CATALOGUE: dict[str, Dictionary] = _catalogue()


def dictionary_for(language: str, german_variant: str = "AT") -> Dictionary | None:
    """The dictionary that checks `language` (a code as languages.py has it), or None when there is none."""
    language = language.lower()
    if language == "de":
        return CATALOGUE.get(f"de_{german_variant}")
    return CATALOGUE.get(language)


def supported_languages() -> set[str]:
    return {entry.language for entry in CATALOGUE.values()}
