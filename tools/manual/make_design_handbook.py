"""Generate the design handbook's tables and offscreen kit pictures.

Run with the repository venv: python tools/manual/make_design_handbook.py.
--text-only needs no QApplication; --output selects a throwaway project for drift checks.
"""
from __future__ import annotations

import argparse
from dataclasses import fields
import os
from pathlib import Path
import re
import sys

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / 'src'))
from slidemage.plugin_api import ThemeTokens
from slidemage.ui.kit import tokens as t

PROJECT = REPO / 'docs/design-handbook'
PUBLIC = {f.name for f in fields(ThemeTokens)}
ROLES = {
    'bg': 'page', 'surface': 'card', 'text': 'primary text', 'text_2': 'secondary text',
    'text_3': 'metadata', 'text_4': 'placeholder / disabled', 'line': 'hairline',
    'hover': 'hover wash', 'inverse': 'primary fill', 'on_inverse': 'text on primary fill',
    'focus': 'keyboard focus', 'on_solid': 'text on solid fill',
    'cloud_solid': 'Cloud route fill', 'paper': 'slide paper', 'paper_text': 'paper text', 'paper_outline': 'image boundary',
    'log_text': 'dark log text', 'scrim': 'overlay base',
    'stage_bg': 'stage background', 'stage_panel': 'presenter panel', 'stage_text': 'stage text',
    'stage_muted': 'secondary stage text', 'stage_active': 'active tool',
    'stage_warn': 'timer warning', 'stage_over': 'timer overdue', 'stage_scrim': 'stage overlay',
    'stage_on_solid': 'text on stage fill', 'stage_paper': 'stage paper',
    'stage_canvas': 'canvas surround', 'stage_name': 'slide name', 'strip': 'presenter strip (px)',
    'toast': 'presenter toast (px)',
}
TYPE_ROLES = dict(zip(('micro', 'small', 'body', 'control', 'heading', 'title', 'display'),
    ('badges / mono metadata', 'captions / chips / tabs', 'labels / chat / source',
     'forms / lists', 'sections / task titles', 'sheet / detail titles', 'job percentage / picker')))
WIDGETS = ('card', 'chip', 'badge', 'row-button', 'segmented-control', 'label', 'icon-button')


def tex(value: object) -> str:
    return str(value).replace('\\', r'\textbackslash{}').replace('_', r'\_').replace('#', r'\#').replace('&', r'\&')


def role(name: str) -> str:
    if name in ROLES:
        return ROLES[name]
    if name.startswith('view_'):
        return name.removeprefix('view_').replace('_tint', ' tint') + ' view only'
    for family in ('info', 'ok', 'warning', 'error'):
        if name.startswith(family):
            return {'': 'text / icon', '_bg': 'tint background', '_fg': 'text on tint',
                    '_solid': 'solid fill'}[name[len(family):]]
    return 'categorical hue'


def swatch(value: object) -> str:
    value = str(value)
    if value.startswith('rgba'):
        r, g, b, a = map(float, re.findall(r'[\d.]+', value))
        colour = ''.join(f'{round(c * a + 255 * (1-a)):02x}' for c in (r, g, b))
    elif value.startswith('#'):
        colour = value[1:]
    else:
        return tex(value)
    return r'\textcolor[HTML]{' + colour + r'}{\rule{1.2em}{0.8em}}\ ' + tex(value)


def table(headers: tuple[str, ...], rows: list[list[str]]) -> str:
    return ('% Generated by tools/manual/make_design_handbook.py; do not edit.\n'
            + r'{\fontsize{7}{9}\selectfont\renewcommand{\arraystretch}{1.18}' + '\n'
            + r'\begin{tabular}{@{}' + 'l' * len(headers) + r'@{}}' + '\n'
            + ' & '.join(r'\textbf{' + h + '}' for h in headers) + r'\\\hline' + '\n'
            + '\n'.join(' & '.join(row) + r'\\' for row in rows)
            + '\n' + r'\end{tabular}}' + '\n')


def text_snippets() -> dict[str, str]:
    """Pure deterministic text generation; all values and API flags come from live definitions."""
    result = {}
    groups = {
        'neutrals': ('bg', 'surface', 'text', 'text_2', 'text_3', 'text_4', 'line', 'hover', 'inverse', 'on_inverse', 'focus'),
        'status': tuple(f + s for f in ('info', 'ok', 'warning', 'error') for s in ('', '_bg', '_fg')),
        'solids': ('error_solid', 'warning_solid', 'on_solid'),
        'views': tuple(f'view_{v}{s}' for v in t.VIEWS for s in ('', '_tint')),
        'fixed': tuple(t.FIXED),
    }
    for group, names in groups.items():
        result[group + '.tex'] = table(('Token', 'Light', 'Dark', 'Role', 'Plugin'), [
            [tex(n), swatch(getattr(t.LIGHT, n)), swatch(getattr(t.DARK, n)), tex(role(n)),
             'yes' if n in PUBLIC else 'core only'] for n in names])
    result['accents.tex'] = table(('Accent', 'Light', 'Dark', 'Role', 'Plugin'), [
        [tex(n), swatch(v), swatch(t.ACCENTS['dark'][n]), role(n), 'accents' if 'accents' in PUBLIC else 'core only']
        for n, v in t.ACCENTS['light'].items()])
    result['stage.tex'] = table(('Token', 'Fixed value', 'Role', 'Plugin'), [
        [tex(f.name), swatch(getattr(t.STAGE, f.name)), tex(role(f.name)), 'core only'] for f in fields(t.STAGE)])
    result['type.tex'] = table(('TYPE', 'px', 'Role', 'Plugin field'), [
        [tex(f.name), str(getattr(t.TYPE, f.name)), TYPE_ROLES[f.name], tex('font_' + f.name)
         if 'font_' + f.name in PUBLIC else 'core only'] for f in fields(t.TYPE)])
    result['space.tex'] = table(('SPACE', 'px', 'Plugin field'), [
        [tex(f.name), str(getattr(t.SPACE, f.name)), tex('space_' + f.name.removeprefix('s_'))
         if 'space_' + f.name.removeprefix('s_') in PUBLIC else 'core only'] for f in fields(t.SPACE)])
    result['radius.tex'] = table(('Corner token', 'px', 'Role', 'Plugin'), [
        [tex(n), str(getattr(t, n)), r, tex(n.lower()) if n.lower() in PUBLIC else 'core only']
        for n, r in [('RADIUS_XS', 'small corners'), ('RADIUS_SM', 'fields'), ('RADIUS_MD', 'cards'),
                     ('RADIUS_LG', 'large corners'), ('RADIUS_PILL', 'legacy; use pill(height)')]])
    return result


def generate_text(output: Path) -> None:
    folder = output / 'snippets'
    folder.mkdir(parents=True, exist_ok=True)
    for name, content in text_snippets().items():
        (folder / name).write_text(content, encoding='utf-8')


def expected_images() -> tuple[str, ...]:
    return tuple(f'{widget}-{theme}.png' for theme in ('light', 'dark') for widget in WIDGETS)


def generate_images(output: Path) -> None:
    # Same offscreen, bundled-font and settled-layout approach as make_screenshots.py.
    os.environ.setdefault('QT_QPA_PLATFORM', 'offscreen')
    os.environ['QT_SCALE_FACTOR'] = '2'
    from PySide6.QtCore import Qt
    from PySide6.QtGui import QColor, QPalette
    from PySide6.QtWidgets import QApplication, QVBoxLayout, QWidget
    from slidemage.ui.kit.fonts import load_fonts
    from slidemage.ui.kit.gallery import KitGallery
    from slidemage.ui.kit.theme import ThemeManager
    from slidemage.ui.kit.widgets import Badge, Chip, IconButton, RowButton, text_label

    app = QApplication.instance() or QApplication([])
    load_fonts()
    folder = output / 'media'
    folder.mkdir(parents=True, exist_ok=True)
    for mode in ('light', 'dark'):
        theme = ThemeManager(dark=mode == 'dark')
        theme.apply()
        gallery = KitGallery(theme)
        row = RowButton('description', 'Selected slide', 'Standard selection', selectable=True)
        row.set_selected(True)
        # Reuse gallery arrangements; supplement widgets not yet in its main window.
        pictures = {'card': gallery._card(), 'chip': gallery._rows(gallery._chips(),
                    gallery._row(Chip('1-0-0', mono=True))),
                    'badge': gallery._row(*(Badge('3', tone) for tone in ('neutral', 'info', 'error'))),
                    'row-button': row, 'segmented-control': gallery._segmented(),
                    'label': gallery._row(*(text_label(r.title(), r) for r in ('title', 'heading', 'body', 'caption'))),
                    'icon-button': gallery._row(IconButton('more_vert', 'More'),
                                               IconButton('more_vert', 'More', faint=True))}
        for name, widget in pictures.items():
            wrapper = QWidget()
            wrapper.setAttribute(Qt.WidgetAttribute.WA_DontShowOnScreen)
            palette = wrapper.palette()
            palette.setColor(QPalette.ColorRole.Window, QColor(theme.tokens.bg))
            wrapper.setPalette(palette)
            wrapper.setAutoFillBackground(True)
            QVBoxLayout(wrapper).addWidget(widget)
            wrapper.resize(max(500, wrapper.sizeHint().width()), wrapper.sizeHint().height())
            wrapper.show()
            for _ in range(5):
                app.processEvents()
            if not wrapper.grab().save(str(folder / f'{name}-{mode}.png')):
                raise RuntimeError(f'Could not save {name}-{mode}')
            wrapper.close()
            wrapper.deleteLater()
        gallery.close()
        gallery.deleteLater()
        app.processEvents()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=PROJECT)
    parser.add_argument('--text-only', action='store_true')
    args = parser.parse_args()
    generate_text(args.output)
    if not args.text_only:
        generate_images(args.output)


if __name__ == '__main__':
    main()
